"""Pack original ChromaticSurface captures for the site's compatible buttons.

Input: output/playwright/material-frames/{pill,circle}-{00..63}.png.
These are product-specific rendered artwork, not a component distribution.
"""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parent.parent
destination = root / 'public/materials'
destination.mkdir(parents=True, exist_ok=True)
for shape in ('pill', 'circle'):
    frames = [Image.open(root / f'output/playwright/material-frames/{shape}-{i:02}.png').convert('RGBA') for i in range(64)]
    width, height = frames[0].size
    assert all(frame.size == (width, height) for frame in frames)
    assert frames[0].getpixel((0, 0))[3] == 0, 'Capture must have a transparent background'
    atlas = Image.new('RGBA', (width * 8, height * 8))
    for i, frame in enumerate(frames):
        atlas.paste(frame, ((i % 8) * width, (i // 8) * height))
    path = destination / f'chromatic-{shape}.webp'
    atlas.save(path, 'WEBP', quality=94, method=6)
    print(shape, atlas.size, path.stat().st_size)

# Travel forwards then backwards through the captured field: no loop seam,
# and CSS can pause at the current frame as soon as hover/focus/visibility ends.
sequence = list(range(64)) + list(range(62, 0, -1))
lines = ['/* Generated by scripts/pack-compatible-material.py. */', '@keyframes chromatic-material-frames {']
for step, frame in enumerate(sequence + [0]):
    lines.append(f'  {step / len(sequence) * 100:.6f}% {{ background-position: {frame % 8 / 7 * 100:.6f}% {frame // 8 / 7 * 100:.6f}%; }}')
lines.append('}')
(root / 'src/components/reactdrops/chromatic-compatible-frames.css').write_text('\n'.join(lines) + '\n', encoding='utf-8')
